// Generates supabase/seed.sql from content/posts/*.md
// so the Supabase table can be seeded from the SQL editor
// (no service-role key required).
//
// Run: node scripts/seed-sql.mjs
// Then paste/run supabase/seed.sql in the Supabase SQL editor.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const postsDir = path.join(root, "content", "posts");
const outFile = path.join(root, "supabase", "seed.sql");

const TAG = "$codelydev_md$";

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, content: raw };
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const sep = line.indexOf(":");
    if (sep === -1) continue;
    const key = line.slice(0, sep).trim();
    let value = line.slice(sep + 1).trim();
    if (!key) continue;

    if (value.startsWith("[") && value.endsWith("]")) {
      data[key] = value
        .slice(1, -1)
        .split(",")
        .map((v) => v.trim().replace(/^["']|["']$/g, ""))
        .filter(Boolean);
    } else if (value === "true" || value === "false") {
      data[key] = value === "true";
    } else {
      data[key] = value.replace(/^["']|["']$/g, "");
    }
  }
  return { data, content: raw.slice(match[0].length) };
}

const q = (s) => String(s).replace(/'/g, "''");
const arr = (list) =>
  `array[${list.map((t) => `'${q(t)}'`).join(", ")}]::text[]`;

const files = fs.existsSync(postsDir)
  ? fs.readdirSync(postsDir).filter((f) => f.endsWith(".md"))
  : [];

if (files.length === 0) {
  console.error("No posts found in content/posts — nothing to seed.");
  process.exit(1);
}

const rows = files.map((file) => {
  const raw = fs.readFileSync(path.join(postsDir, file), "utf8");
  const { data, content } = parseFrontmatter(raw);
  const slug = file.replace(/\.md$/, "");
  if (content.includes(TAG)) {
    throw new Error(`Content of ${file} contains the ${TAG} delimiter`);
  }

  return `(
  '${q(slug)}',
  '${q(data.title ?? slug)}',
  '${q(data.excerpt ?? data.description ?? "")}',
  ${TAG}${content}${TAG},
  ${arr(Array.isArray(data.tags) ? data.tags : [])},
  '${q(data.author ?? "CodelyDev Team")}',
  '${q(data.cover ?? "navy")}',
  ${data.featured === true},
  '${q(data.date ?? "2026-01-01")}'::date,
  true
)`;
});

const sql = `-- ============================================================
-- CodelyDev — seed.sql (AUTO-GENERATED by scripts/seed-sql.mjs)
-- Imports the starter posts from content/posts/*.md.
-- Safe to re-run: existing slugs are left untouched.
-- ============================================================

insert into public.posts
  (slug, title, excerpt, content, tags, author, cover, featured, date, published)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, sql, "utf8");
console.log(`wrote supabase/seed.sql (${rows.length} posts, ${sql.length} bytes)`);
